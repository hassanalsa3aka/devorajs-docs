#!/usr/bin/env node
// Turns a Markdown guide into a docs-site route (apps/docs/routes/<name>.tsx): headings, paragraphs, lists, tables, fenced code,
// inline code, bold and links. The Markdown in apps/docs/content/ is the source; the route is generated, so edit the Markdown and rerun.
//   node scripts/md-to-page.mjs apps/docs/content/sekhem.md sekhem "Sekhem: the engine of our own" "description for the meta tag"
import fs from "node:fs";
import path from "node:path";

const [src, name, title, description] = process.argv.slice(2);
if (!src || !name || !title || !description) throw new Error("usage: md-to-page.mjs <file.md> <route-name> <title> <description>");
const lines = fs.readFileSync(src, "utf8").split("\n");

const esc = (t) => t.replace(/[{}<>&]/g, (c) => ({ "{": "&#123;", "}": "&#125;", "<": "&lt;", ">": "&gt;", "&": "&amp;" })[c]);
const inline = (t) => {
  const parts = [];
  let rest = t;
  const re = /`([^`]+)`|\*\*([^*]+)\*\*|\[([^\]]+)\]\(([^)]+)\)/;
  for (;;) {
    const m = re.exec(rest);
    if (!m) {
      parts.push(esc(rest));
      break;
    }
    parts.push(esc(rest.slice(0, m.index)));
    if (m[1] !== undefined) parts.push(`<code>${esc(m[1])}</code>`);
    else if (m[2] !== undefined) parts.push(`<strong>${inline(m[2])}</strong>`);
    else parts.push(`<a href="${m[4].replace(/"/g, "&quot;")}">${inline(m[3])}</a>`);
    rest = rest.slice(m.index + m[0].length);
  }
  return parts.join("");
};
const slug = (t) => t.toLowerCase().replace(/`/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const tpl = (code) => "{`" + code.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`}";

const out = [];
let i = 0;
let leadDone = false;
while (i < lines.length) {
  const line = lines[i];
  if (line.startsWith("```")) {
    const code = [];
    i++;
    while (i < lines.length && !lines[i].startsWith("```")) code.push(lines[i++]);
    i++;
    out.push(`        <pre><code>${tpl(code.join("\n"))}</code></pre>`);
  } else if (line.startsWith("# ")) {
    out.push(`        <h1>${inline(line.slice(2))}</h1>`);
    i++;
  } else if (line.startsWith("## ")) {
    out.push(`        <h2 id="${slug(line.slice(3))}">${inline(line.slice(3))}</h2>`);
    i++;
  } else if (line.startsWith("### ")) {
    out.push(`        <h3>${inline(line.slice(4))}</h3>`);
    i++;
  } else if (line.startsWith("|")) {
    const rows = [];
    while (i < lines.length && lines[i].startsWith("|")) rows.push(lines[i++]);
    const cells = (r) => r.replace(/^\||\|$/g, "").split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, "|"));
    const head = cells(rows[0]);
    const body = rows.slice(2).map(cells);
    out.push(`        <div className="docs-table-wrap">\n          <table>\n            <thead><tr>${head.map((h) => `<th>${inline(h)}</th>`).join("")}</tr></thead>\n            <tbody>\n${body.map((r) => `              <tr>${r.map((c) => `<td>${inline(c)}</td>`).join("")}</tr>`).join("\n")}\n            </tbody>\n          </table>\n        </div>`);
  } else if (/^- /.test(line)) {
    const items = [];
    while (i < lines.length && (/^- /.test(lines[i]) || /^  \S/.test(lines[i]))) {
      if (/^- /.test(lines[i])) items.push(lines[i].slice(2));
      else items[items.length - 1] += " " + lines[i].trim();
      i++;
    }
    out.push(`        <ul>\n${items.map((t) => `          <li>${inline(t)}</li>`).join("\n")}\n        </ul>`);
  } else if (line.trim() === "") {
    i++;
  } else {
    const para = [];
    while (i < lines.length && lines[i].trim() !== "" && !/^(#|```|\||- )/.test(lines[i])) para.push(lines[i++]);
    const cls = !leadDone ? ' className="devora-lead"' : "";
    leadDone = true;
    out.push(`        <p${cls}>${inline(para.join(" "))}</p>`);
  }
}

const tsx = `// Generated by scripts/md-to-page.mjs from apps/docs/content/${path.basename(src)}: edit the Markdown, not this file.
import { PageShell } from "@devorajs/core";
import { DOCS_NAV } from "../nav.js";
import { SiteFooter } from "../site-footer.js";
import { DocsLayout } from "../docs-layout.js";
import { pageMeta } from "../seo.js";

export const renderMode = "ssg";

export function meta() {
  return pageMeta("/${name}", {
    title: ${JSON.stringify(title)},
    description: ${JSON.stringify(description)},
  });
}

export async function loader() {
  return {};
}

export default function Page() {
  return (
    <PageShell nav={DOCS_NAV} footer={<SiteFooter />}>
      <DocsLayout active="${name}">
${out.join("\n")}
      </DocsLayout>
    </PageShell>
  );
}
`;
fs.writeFileSync(path.join("apps/docs/routes", `${name}.tsx`), tsx);
console.log(`wrote apps/docs/routes/${name}.tsx (${out.length} blocks)`);
